    private void displayBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_displayBtnActionPerformed
        displayTF.setText("");
        if (quotes.isEmpty()) {
            JOptionPane.showMessageDialog(this, "there a no quotes to print");
        } else {
            for (String q : quotes) {
                displayTF.append(q + "\n");
            }
        }
    }//GEN-LAST:event_displayBtnActionPerformed

    private void nextBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_nextBtnActionPerformed
        if (quotes.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No quotes available");
            return;
        }

        if (index >= quotes.size()) {
            index = 0;
        }

        displayTF.setText(quotes.get(index));
        index++;
    }//GEN-LAST:event_nextBtnActionPerformed

    private void save() {
        try (ObjectOutputStream oStream = new ObjectOutputStream(new FileOutputStream("quotes.dat"))) {
            oStream.writeObject(quotes);
            JOptionPane.showMessageDialog(this, "File saved successfully");
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "An error occurred while saving. " + e.getMessage());
        }
    }

    private void load() {
        try (ObjectInputStream oStream = new ObjectInputStream(new FileInputStream("quotes.dat"))) {
            quotes = (ArrayList<String>) oStream.readObject();
            JOptionPane.showMessageDialog(this, "Quotes Loaded sucessfully");
        } catch (FileNotFoundException e) {
            JOptionPane.showMessageDialog(this, "The data file output.dat was not found. Please save before trying to load.");
            quotes = new ArrayList<>();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "An error occurred while reading the file." + e.getMessage());
        } catch (ClassNotFoundException e) {
            JOptionPane.showMessageDialog(this, "Class mismatch when loading quotes");
        }
    }

    private void randomQuote() {
        if (quotes.isEmpty()) {
            displayTF.setText("No quotes available");
            return;
        }

        int randomIndex = (int) (Math.random() * quotes.size());
        displayTF.setText(quotes.get(randomIndex));

        // keep index in sync with Next button
        index = randomIndex + 1;
    }

